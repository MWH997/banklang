/** The domain the site is served from, for canonical and Open Graph URLs. */
export const SITE_ORIGIN = "https://banklang.mwhassan.com";

/**
 * The URL a built file is actually served at.
 *
 * Cloudflare Pages does not serve `.html`. A request for `/docs/glossary.html`
 * is answered with a 308 to `/docs/glossary`, and `/docs/index.html` with a 308
 * to `/docs/`. Everything this build writes lands on disk as `.html`, so the
 * path a file has and the URL it answers on are two different strings — and
 * every canonical, `og:url`, sitemap entry and feed link has to use the second.
 *
 * F11 is what happens when they are written out by hand instead. Forty-seven of
 * fifty-one sitemap entries named the redirecting form, which Search Console
 * reports as "Page with redirect, not indexed", and the two indexes disagreed
 * with each other: the docs index declared `…/docs/index.html` canonical while
 * its own sitemap entry said `…/docs/`. One page, two URLs, and a search engine
 * choosing between them.
 *
 * Derived here so there is one rule. `tests/docs-site.test.ts` holds every
 * sitemap entry to the canonical of the page it names, which is the invariant
 * that was broken rather than a restatement of this function.
 */
export function servedPath(builtPath: string): string {
  const path = builtPath.replace(/\\/g, "/").replace(/^\/+/, "");
  if (path === "index.html") {
    return "/";
  }
  if (path.endsWith("/index.html")) {
    return `/${path.slice(0, -"index.html".length)}`;
  }
  return `/${path.replace(/\.html$/, "")}`;
}

/** The absolute URL a built file is served at. */
export function servedUrl(builtPath: string): string {
  return `${SITE_ORIGIN}${servedPath(builtPath)}`;
}

/**
 * The theme control, which is a toggle button rather than an action.
 *
 * E5. It read `Theme` with an `aria-label` of "Switch between light and dark",
 * no `aria-pressed`, and a label that never changed — so neither a sighted nor
 * a screen-reader user could tell the current mode from the control.
 *
 * The label names what is being toggled and `aria-pressed` says whether it is
 * on. The ticket's other suggestion was a label naming the destination, "Dark"
 * while light and "Light" while dark, and the two cannot both be right: a
 * control whose label is where it takes you is an action, and `aria-pressed` on
 * an action announces a state its own label contradicts.
 *
 * Held here, so the documentation and blog shells cannot drift from each other.
 * `packages/site/src/index.html` and the playground carry their own copy —
 * neither is generated by this file — and `tests/site.test.ts` holds all four
 * to the same behaviour.
 */
export const THEME_BUTTON = `<button id="theme" type="button" class="ghost" aria-pressed="false">Dark mode</button>`;

export const THEME_SCRIPT = `    <script>
      (() => {
        const button = document.getElementById("theme");
        const root = document.documentElement;
        const dark = matchMedia("(prefers-color-scheme: dark)");
        const isDark = () =>
          root.dataset.theme === "dark" || (!root.dataset.theme && dark.matches);
        const sync = () => button.setAttribute("aria-pressed", String(isDark()));
        sync();
        // The preference can change without a click, and then the button is
        // announcing a state that is no longer true.
        dark.addEventListener("change", sync);
        button.addEventListener("click", () => {
          root.dataset.theme = isDark() ? "light" : "dark";
          localStorage.setItem("banklang-theme", root.dataset.theme);
          sync();
        });
      })();
    </script>`;

/* ------------------------------------------------------------------ *
 * Syntax highlighting, at build time.
 *
 * L2: no runtime JavaScript beyond the theme toggle. A highlighter shipped to
 * the browser to colour four code blocks is 40 KB to do what a build can do
 * once. These are deliberately small — enough for the constructs on this page.
 * ------------------------------------------------------------------ */

export const escapeHtml = (text: string): string =>
  text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const BANKTS_KEYWORDS =
  /\b(module|type|record|function|transaction|return|let|if|else|for|each|in|raise|on|failure|file|test|currency|decimal|string|bool|date|enum|extends)\b/g;

export function highlightBankTs(code: string): string {
  return escapeHtml(code)
    .replace(/(\/\/[^\n]*)/g, '<span class="c-com">$1</span>')
    .replace(/(&quot;[^&]*?&quot;)/g, '<span class="c-str">$1</span>')
    .replace(BANKTS_KEYWORDS, '<span class="c-kw">$1</span>')
    .replace(/\b(\d+(?:\.\d+)?)\b/g, '<span class="c-num">$1</span>');
}

/**
 * COBOL in fixed reference format.
 *
 * The indicator area matters: an asterisk or `*>` in column 7 is a comment, and
 * colouring it as code would misrepresent the output on the one page where a
 * mainframe engineer is deciding whether the output is readable.
 */
export function highlightCobol(code: string): string {
  return code
    .split("\n")
    .map((line) => {
      const escaped = escapeHtml(line);
      if (/^.{6}[*/]/.test(line) || /^\s*\*>/.test(line)) {
        return `<span class="c-com">${escaped}</span>`;
      }
      return escaped
        .replace(/(&quot;[^&]*?&quot;)/g, '<span class="c-str">$1</span>')
        .replace(
          /\b(IDENTIFICATION|ENVIRONMENT|DATA|PROCEDURE|DIVISION|SECTION|PROGRAM-ID|MOVE|COMPUTE|IF|ELSE|END-IF|EVALUATE|WHEN|END-EVALUATE|PERFORM|CALL|GO TO|GOBACK|ADD|SUBTRACT|MULTIPLY|DIVIDE|OPEN|CLOSE|READ|WRITE|EXEC|END-EXEC|PIC|VALUE|COMP-3|OCCURS|FUNCTION|ON SIZE ERROR|END-COMPUTE|DISPLAY|UPON|THRU|USING|TO|FROM|BY|INTO)\b/g,
          '<span class="c-kw">$1</span>',
        )
        .replace(/\b(\d+(?:\.\d+)?)\b/g, '<span class="c-num">$1</span>');
    })
    .join("\n");
}

